/* Digi Macro: the MACRO machine, engines ported from Plaits by Emilie Gillet (macro.c, MIT licence), as one
 * of Digi Mono's machines (mods/digimono/digimono_ext.h): Digi Mono renders its voices, on its own stack, with its
 * overload guard, and draws its knobs; this mod brings the engines, their state and the knobs' names.
 *
 * Two registrations: the machine list entry (core 2.1's core_machines: id 27, MACRO, its icon; ONESHOT's
 * parameters and render, as Digi Mono's own machines) and the engine (Digi Mono's digimono_ext). */
#ifdef OS154
#define BMP_VT 0x401b7734u                  /* the firmware's Bitmap vtable (tools/os154.json) */
#else
#define BMP_VT 0x401b73b4u
#endif

#include "macro.h"
#include "digimono_ext.h"

/* ---- the engines: a voice's struct macro_voice in Digi Mono's voice (digimono_ext.h) ----------------- */
static void dmx_init(void *st)
{
    macro_init((struct macro_voice *)st);
}

static void dmx_trig(void *st)
{
    macro_trig((struct macro_voice *)st);
}

static void dmx_render(void *st, const uint8_t *p, uint32_t inc, int16_t *out, int n)
{
    macro_render((struct macro_voice *)st, p, inc, out, n);
}

/* ---- the knobs: B ENGN, C HARM, E MORP, D TIMB (MACRO.md) ------------------------------------------- */
static const int8_t knob_p[DIGIMONO_EXT_KNOBS] = {0, 1, 3, -1, -1, -1, 2};      /* B C E F G H D */
static const uint8_t knob_def[DIGIMONO_EXT_KNOBS] = {0, 64, 64, 0, 0, 0, 64};   /* the first engine, the middles */
static const char *const knob_sname[DIGIMONO_EXT_KNOBS] = {"ENGN", "HARM", "MORP", "-", "-", "-", "TIMB"};
static const char *const knob_lname[DIGIMONO_EXT_KNOBS] = {"Engine", "Harmonics", "Morph", "-", "-", "-", "Timbre"};

/* B shows the engine's name; the others their number */
static int knob_text(int k, int v, char *buf)
{
    const char *s;
    if (k != 0)
        return 0;
    s = macro_engine_name[macro_engine_of(v)];
    while ((*buf++ = *s++))
        ;
    return 1;
}

const struct digimono_ext digimacro_ext = {
    27, sizeof(struct macro_voice), "MACR", knob_p, knob_def, knob_sname, knob_lname, knob_text, dmx_init, dmx_trig, dmx_render,
};

/* ---- the machine list's entry (core 2.1 core_machines; elekloader docs/ADAPTING.md) ------------------ *
 * The icon is a Bitmap as the firmware's own: vtable, width 11, height 7, 1, pixels, mask; one 32-bit
 * word a column, the top row in bit 25 (tools/gen_mono_icons.py, "macr"). */
/* generated by tools/gen_mono_icons.py --c macr */
static const uint32_t icon_px[11] = {
    0x20000000, 0x10000000, 0x08000000, 0x10000000, 0x20000000, 0x40000000,
    0x20000000, 0x10000000, 0x08000000, 0x10000000, 0x20000000,
};
static const uint32_t icon_mask[11] = {
    0xfe000000, 0xfe000000, 0xfe000000, 0xfe000000, 0xfe000000, 0xfe000000,
    0xfe000000, 0xfe000000, 0xfe000000, 0xfe000000, 0xfe000000,
};
struct bitmap {
    uint32_t vt, w, h, one;
    const uint32_t *px, *mask;
    uint32_t end;
};
static const struct bitmap icon = {BMP_VT, 11, 7, 1, icon_px, icon_mask, 0};

/* id, name, short name, icon, params (ONESHOT), render (ONESHOT) */
struct machine {
    uint32_t id;
    const char *name, *sname;
    const struct bitmap *icon;
    uint32_t params, render;
};
const struct machine digimacro_m27 = {27, "MACRO", "MACR", &icon, 0, 0};
